#!/usr/bin/env python3
"""Turns a potrace SVG of the Racha emblem strokes into brand assets.

usage: python3 tools/potrace_to_brand.py <potrace.svg> <repo root>
Writes design/brand/*.svg, the Android adaptive-icon foreground and the Compose RachaLogo vector.
Trace with: potrace -s -t 300 -a 1.3 -O 0.3 (input: 1024x1024 bitmap of the strokes, see docs/DISENO.md).
"""
import re
import sys

NAVY = '#212A41'          # sampled from the original icon background
STROKE_TOP = '#F3B65C'    # yellow tips of the flame
STROKE_BOTTOM = '#DD7552' # coral ring bottom
SRC = 1024.0


def absolute_paths(svg_text):
    """potrace emits m/l/c/z (mostly relative) under translate(0,H) scale(0.1,-0.1): return absolute y-down paths."""
    paths = re.findall(r'<path d="([^"]+)"', svg_text)
    out = []
    for d in paths:
        tokens = re.findall(r'[MmLlCcZz]|-?\d*\.?\d+', d)
        i, cmd, cx, cy, sx, sy = 0, None, 0.0, 0.0, 0.0, 0.0
        segs = []
        def pt(x, y):
            return (x * 0.1, SRC - y * 0.1)
        while i < len(tokens):
            t = tokens[i]
            if re.match(r'[MmLlCcZz]', t):
                cmd = t
                i += 1
                if cmd in 'Zz':
                    segs.append(('Z',))
                    cx, cy = sx, sy
                continue
            if cmd in 'Mm':
                x, y = float(tokens[i]), float(tokens[i + 1]); i += 2
                if cmd == 'm' and segs:
                    x, y = cx + x, cy + y
                cx, cy, sx, sy = x, y, x, y
                segs.append(('M', pt(x, y)))
                cmd = 'l' if cmd == 'm' else 'L'
            elif cmd in 'Ll':
                x, y = float(tokens[i]), float(tokens[i + 1]); i += 2
                if cmd == 'l':
                    x, y = cx + x, cy + y
                cx, cy = x, y
                segs.append(('L', pt(x, y)))
            elif cmd in 'Cc':
                vals = [float(v) for v in tokens[i:i + 6]]; i += 6
                if cmd == 'c':
                    vals = [cx + vals[0], cy + vals[1], cx + vals[2], cy + vals[3], cx + vals[4], cy + vals[5]]
                cx, cy = vals[4], vals[5]
                segs.append(('C', pt(vals[0], vals[1]), pt(vals[2], vals[3]), pt(vals[4], vals[5])))
            else:
                raise SystemExit(f'unexpected command {cmd}')
        out.append(segs)
    return out


def render(paths, scale, dx, dy):
    def f(v):
        s = ('%.2f' % v).rstrip('0').rstrip('.')
        return '0' if s in ('-0', '') else s
    def p(q):
        return f'{f(q[0] * scale + dx)} {f(q[1] * scale + dy)}'
    parts = []
    for segs in paths:
        for s in segs:
            if s[0] == 'Z':
                parts.append('Z')
            elif s[0] in 'ML':
                parts.append(f'{s[0]}{p(s[1])}')
            else:
                parts.append(f'C{p(s[1])} {p(s[2])} {p(s[3])}')
    return ''.join(parts)


def main(svg, root):
    paths = absolute_paths(open(svg).read())
    full = render(paths, 1, 0, 0)
    gradient = (f'<linearGradient id="flame" x1="0" y1="0" x2="0" y2="1024" gradientUnits="userSpaceOnUse">'
                f'<stop offset="0" stop-color="{STROKE_TOP}"/><stop offset="1" stop-color="{STROKE_BOTTOM}"/></linearGradient>')
    emblem = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><defs>{gradient}</defs>'
              f'<circle cx="512" cy="512" r="500" fill="{NAVY}"/><path fill="url(#flame)" fill-rule="evenodd" d="{full}"/></svg>\n')
    icon = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><defs>{gradient}</defs>'
            f'<rect width="1024" height="1024" rx="224" fill="{NAVY}"/>'
            f'<g transform="translate(112 112) scale(0.78125)"><path fill="url(#flame)" fill-rule="evenodd" d="{full}"/></g></svg>\n')
    open(f'{root}/design/brand/racha-emblem.svg', 'w').write(emblem)
    open(f'{root}/design/brand/racha-icon.svg', 'w').write(icon)

    # Android adaptive icon: 108 dp canvas, emblem 66 dp wide centred (inside the 72 dp visible area).
    size, offset = 66.0, (108 - 66) / 2
    android = render(paths, size / SRC, offset, offset)
    fg = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/potrace_to_brand.py from design/brand (traced from the original Racha icon). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillType="evenOdd"
        android:pathData="{android}">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="54" android:startY="{offset:.1f}"
                android:endX="54" android:endY="{offset + size:.1f}"
                android:startColor="{STROKE_TOP}"
                android:endColor="{STROKE_BOTTOM}" />
        </aapt:attr>
    </path>
</vector>
'''
    mono = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Themed-icon (monochrome) layer: same strokes, solid. Generated by tools/potrace_to_brand.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillType="evenOdd" android:fillColor="#FFFFFFFF" android:pathData="{android}" />
</vector>
'''
    res = f'{root}/client/android/src/main/res'
    open(f'{res}/drawable/ic_launcher_foreground.xml', 'w').write(fg)
    open(f'{res}/drawable/ic_launcher_monochrome.xml', 'w').write(mono)

    compose_path = render(paths, 1, 0, 0)
    kt = f'''package io.github.roberbarras.racha.ui.design

import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.graphics.Brush
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.PathFillType
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

// Generated by tools/potrace_to_brand.py from the original Racha icon (design/brand). Do not edit by hand.

/** The Racha emblem: navy disc, flame strokes with a yellow-to-coral gradient. 1024-unit viewport. */
val RachaLogo: ImageVector by lazy {{
    ImageVector.Builder("racha", 108.dp, 108.dp, 1024f, 1024f).apply {{
        addPath(addPathNodes("M12 512a500 500 0 1 0 1000 0a500 500 0 1 0-1000 0z"), fill = SolidColor(Color(0xFF{NAVY[1:]})))
        addPath(
            pathData = addPathNodes(EMBLEM_STROKES),
            pathFillType = PathFillType.EvenOdd,
            fill = Brush.linearGradient(listOf(Color(0xFF{STROKE_TOP[1:]}), Color(0xFF{STROKE_BOTTOM[1:]})), Offset(512f, 0f), Offset(512f, 1024f)),
        )
    }}.build()
}}

/** Only the flame strokes (transparent background), for drawing over the brand navy (e.g. the launch animation). */
val RachaFlame: ImageVector by lazy {{
    ImageVector.Builder("racha-flame", 108.dp, 108.dp, 1024f, 1024f).apply {{
        addPath(
            pathData = addPathNodes(EMBLEM_STROKES),
            pathFillType = PathFillType.EvenOdd,
            fill = Brush.linearGradient(listOf(Color(0xFF{STROKE_TOP[1:]}), Color(0xFF{STROKE_BOTTOM[1:]})), Offset(512f, 0f), Offset(512f, 1024f)),
        )
    }}.build()
}}

private const val EMBLEM_STROKES = "{compose_path}"
'''
    open(f'{root}/client/shared/ui/src/commonMain/kotlin/io/github/roberbarras/racha/ui/design/RachaLogo.kt', 'w').write(kt)
    print('paths', len(paths), 'android pathData chars', len(android), 'compose chars', len(compose_path))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
